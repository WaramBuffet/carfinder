export function priceSummary(
  listings: MarketListing[],
  carId: string,
  year: number,
  maxKm: number,
  portal: Portal | "all" = "all",
) {
  const unique = new Map<string, MarketListing>();
  for (const listing of listings) {
    if (
      listing.kind !== "purchase" ||
      listing.carId !== carId ||
      listing.year !== year ||
      listing.mileageKm > maxKm ||
      listing.mileageKm < 0 ||
      !Number.isFinite(listing.priceEur) ||
      listing.priceEur <= 0 ||
      !listing.url.startsWith("https://") ||
      !listing.observedAt ||
      !listing.variant ||
      !listing.deduplicationKey ||
      (portal !== "all" && listing.portal !== portal)
    )
      continue;
    if (!unique.has(listing.deduplicationKey)) unique.set(listing.deduplicationKey, listing);
  }
  const rows = [...unique.values()];
  const prices = rows.map((row) => row.priceEur).sort((a, b) => a - b);
  const n = prices.length;
  const mid = Math.floor(n / 2);
  return {
    n,
    mean: n ? prices.reduce((a, b) => a + b, 0) / n : null,
    median: n ? (n % 2 ? prices[mid]! : (prices[mid - 1]! + prices[mid]!) / 2) : null,
    min: n ? prices[0]! : null,
    max: n ? prices[n - 1]! : null,
    rows,
  };
}
